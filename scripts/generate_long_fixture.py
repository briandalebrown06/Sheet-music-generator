"""Original, deterministic DEVELOPMENT audio; reference notes never enter inference."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import wave
from pathlib import Path

import numpy as np


def file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def generate(directory: Path, seconds: int = 720) -> dict:
    directory.mkdir(parents=True, exist_ok=True)
    rate = 44100
    notes = []
    for bar in range(math.ceil(seconds / 4)):
        start = bar * 4
        pitch = [60, 64, 67, 65, 62][bar % 5]
        for offset, duration, delta in [(0.2, .8, 0), (1.4, .65, 3), (2.4, 1.2, 7)]:
            if start + offset + duration < seconds:
                notes.append({"pitch": pitch + delta, "start": start + offset, "end": start + offset + duration})
    # A sustained note crossing a minute boundary and distinct repeated attacks.
    notes = [n for n in notes if not (56 <= n["start"] < 64) and n["start"] < seconds - 4]
    notes.extend([
        {"pitch": 69, "start": 59.5, "end": 61.4},
        {"pitch": 64, "start": 61.7, "end": 62.1},
        {"pitch": 64, "start": 62.3, "end": 62.7},
        {"pitch": 64, "start": seconds - 3.8, "end": seconds - 3.0},
        {"pitch": 67, "start": seconds - 2.6, "end": seconds - 1.95},
        {"pitch": 72, "start": seconds - 1.6, "end": seconds - .2},
    ])
    notes.sort(key=lambda note: note["start"])
    output = directory / f"DEVELOPMENT-{seconds}-second-performance.wav"
    with wave.open(str(output), "wb") as audio:
        audio.setnchannels(2)
        audio.setsampwidth(2)
        audio.setframerate(rate)
        for second in range(seconds):
            time = second + np.arange(rate, dtype=np.float64) / rate
            signal = np.zeros(rate, dtype=np.float64)
            for note in notes:
                if note["end"] <= second or note["start"] >= second + 1:
                    continue
                local = time - note["start"]
                envelope = np.maximum(0, np.minimum(1, np.minimum(local / .02, (note["end"] - time) / .04)))
                frequency = 440 * 2 ** ((note["pitch"] - 69) / 12)
                phase = 2 * np.pi * frequency * local
                signal += .24 * envelope * (np.sin(phase) + .35 * np.sin(phase * 2) + .15 * np.sin(phase * 3))
            stereo = np.column_stack((signal, .9 * signal))
            audio.writeframesraw(np.rint(np.clip(stereo, -1, 1) * 32767).astype("<i2").tobytes())
    manifest = {"development_fixture": True, "license": "Original procedural audio and reference data generated by this repository; CC0-1.0.",
                "duration_seconds": seconds, "sample_rate": rate, "channels": 2, "subtype": "PCM_16",
                "path": output.name, "bytes": output.stat().st_size, "sha256": file_hash(output), "expected_notes": notes}
    (directory / "reference.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    result = generate(args.output)
    print(json.dumps({key: value for key, value in result.items() if key != "expected_notes"}, indent=2))
